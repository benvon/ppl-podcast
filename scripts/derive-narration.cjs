#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");

// Production status remains here solely to strip it from legacy scripts.
const METADATA_LINE = /^\*\*(?:Version|Target runtime|Speakers|Production status):/;
const SOURCE_TAG_LINE = /^\[(?:Source|Claim type):/;

function deriveNarration(markdown) {
  const lines = markdown.replace(/\r\n/g, "\n").split("\n");
  const titleLine = lines.find((line) => /^#\s+\S/.test(line));
  if (!titleLine) throw new Error("master script must contain a title heading");
  const title = titleLine.replace(/^#\s+/, "").trim();
  const body = lines.filter((line) => line !== titleLine && !METADATA_LINE.test(line) && !SOURCE_TAG_LINE.test(line));
  return [
    `# ${title} — narration derivative`,
    "",
    "> Generated from the approved `master-script.md`. Do not edit this file as an",
    "> independent source of truth; make wording changes in the master script first.",
    "",
    ...body,
  ].join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

function parseArgs(argv) {
  const values = {};
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (!argument.startsWith("--")) throw new Error(`Unexpected argument: ${argument}`);
    const value = argv[index + 1];
    if (!value || value.startsWith("--")) throw new Error(`Missing value for ${argument}`);
    values[argument.slice(2)] = value;
    index += 1;
  }
  if (!values.script || !values.output) throw new Error("--script and --output are required.");
  return values;
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const scriptPath = path.resolve(options.script);
  const outputPath = path.resolve(options.output);
  const narration = deriveNarration(fs.readFileSync(scriptPath, "utf8"));
  fs.writeFileSync(outputPath, narration, "utf8");
  console.log(`Wrote ${path.relative(process.cwd(), outputPath)}`);
}

if (require.main === module) {
  try { main(); } catch (error) { console.error(`Narration derivation failed: ${error.message}`); process.exitCode = 1; }
}

module.exports = { deriveNarration };
